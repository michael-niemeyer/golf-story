"""report_numbers.py -- write every number quoted in the LaTeX report as a macro
(report/numbers.tex) plus generated tables, so the report can never drift from the data.

Usage: python3 prep/report_numbers.py   (after prepare.py, grid.py, checks.py)
"""
import json, sys
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "prep"))
import model as M  # noqa: E402

OUT = ROOT / "report"
OUT.mkdir(exist_ok=True)
D = ROOT / "data"
V = json.loads((D / "validation.json").read_text())
CK = json.loads((D / "checks.json").read_text())
GR = json.loads((D / "grid.json").read_text())
TM = json.loads((D / "trackman.json").read_text())
YD, MPH, FT = 0.9144, 0.44704, 0.3048
mac = {}


def m(name, val):
    mac[name] = val


cal = V["calibration"]
m("CalCdOne", f"{cal['Cd1']:.3f}"); m("CalClOne", f"{cal['Cl1']:.3f}")
m("CalCarry", f"{cal['carry_yd']:.1f}"); m("CalErrYd", f"{cal['err_yd']:+.1f}"); m("CalErrPct", f"{cal['err_pct']:+.1f}")
m("CalN", str(cal["search"]["n"]))
row = lambda s, t, c: next(r for r in V["validation"] if r["coef_set"] == s and r["tour"] == t and r["club"] == c)
m("RawDrvCarry", f"{row('raw', 'PGA', 'Driver')['model_carry_yd']:.1f}")
m("RawDrvErr", f"{row('raw', 'PGA', 'Driver')['carry_err_yd']:+.1f}")
m("RawLDrvErr", f"{row('raw', 'LPGA', 'Driver')['carry_err_yd']:+.1f}")
for r in V["mae"]:
    k = ("Raw" if r["coef_set"] == "raw" else "Cal") + r["tour"].replace("LPGA", "L").replace("PGA", "P")
    m("Mae" + k, f"{r['mae_carry_yd']:.1f}"); m("MaeApex" + k, f"{r['mae_apex_yd']:.1f}"); m("MaeLand" + k, f"{r['mae_land_deg']:.1f}")
held = lambda s: np.mean([abs(r["carry_err_yd"]) for r in V["validation"] if r["coef_set"] == s and not (r["tour"] == "PGA" and r["club"] == "Driver")])
m("HeldRaw", f"{held('raw'):.1f}"); m("HeldCal", f"{held('calibrated'):.1f}")
irons = [r for r in V["validation"] if r["coef_set"] == "raw" and ("iron" in r["club"] or r["club"] == "PW")]
m("IronLandErr", f"{np.mean([r['model_land_deg'] - r['measured_land_deg'] for r in irons]):.1f}")
m("IronOutside", f"{100 * min(r['frac_outside'] for r in irons):.0f}")

raw = V["coef_sets"]["raw"]
drv = next(r for r in TM if r["tour"] == "PGA" and r["club"] == "Driver")
base = dict(v0=drv["ball_mph"] * MPH, theta=drv["launch_deg"], rpm=drv["spin_rpm"], Cd1=raw["Cd1"], Cl1=raw["Cl1"])
c0 = M.simulate(**base)["carry"][0]
m("VacDrv", f"{M.vacuum(base['v0'], base['theta'])['range'] / YD:.0f}")
m("VacDrvFortyFive", f"{M.vacuum(base['v0'], 45)['range'] / YD:.0f}")
m("ModDrvFortyFive", f"{M.simulate(**dict(base, theta=45))['carry'][0] / YD:.0f}")
m("HeadLoss", f"{(c0 - M.simulate(**base, wx=-10 * MPH)['carry'][0]) / YD:.0f}")
m("TailGain", f"{(M.simulate(**base, wx=10 * MPH)['carry'][0] - c0) / YD:.0f}")
dv = M.simulate(**base, alt=5280 * FT)
m("DenverGain", f"{(dv['carry'][0] - c0) / YD:.0f}"); m("DenverRho", f"{dv['rho'][0]:.3f}")
m("SmoothCarry", f"{M.simulate(**base, dimples=False)['carry'][0] / YD:.0f}")
fade = M.simulate(**base, alpha=8)
m("FadeLat", f"{fade['lateral'][0] / YD:.1f}")
dragonly = M.simulate(**base, mode="drag")["carry"][0]
m("DragOnly", f"{dragonly / YD:.0f}")

L = GR["sets"]["raw"]["171"]; nW = len(GR["rpm"])
b = int(np.argmax(L["carry10"]))
m("OptCarry", f"{L['carry10'][b] / 10:.0f}"); m("OptTheta", f"{GR['theta'][b // nW]:.1f}"); m("OptRpm", f"{GR['rpm'][b % nW]}")
m("NSpeeds", str(len(GR["speeds_mph"]))); m("NGridRuns", f"{2 * len(GR['speeds_mph']) * len(GR['theta']) * nW:,}".replace(",", "{,}"))
ts = V["table_sizes"]
m("NRuns", str(ts["runs"])); m("NTraj", f"{ts['trajectory']:,}".replace(",", "{,}"))
m("NChecks", str(len(CK["checks"]))); m("NPass", str(sum(c["passed"] for c in CK["checks"])))
W = CK["worked_example"]["hand"]
for k, f in [("S0", ".4f"), ("CD0", ".4f"), ("CL0", ".4f"), ("FD0_N", ".3f"), ("FL0_N", ".3f"), ("weight_N", ".3f")]:
    m("W" + k.replace("0_N", "").replace("_N", "").replace("0", "zero"), format(W[k], f))
m("WRe", f"{W['Re0']:,.0f}".replace(",", "{,}"))

(OUT / "numbers.tex").write_text("% generated by prep/report_numbers.py -- do not edit\n" +
                                 "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in mac.items()) + "\n")


def esc(s):
    s = str(s).replace("v0^2 sin2θ/g", "\x01").replace("2v0/g", "\x02")
    return (s.replace("\\", "\\textbackslash{}").replace("&", "\\&").replace("%", "\\%").replace("_", "\\_")
            .replace("#", "\\#").replace("Δ", "$\\Delta$").replace("θ0", "$\\theta_0$").replace("θ", "$\\theta$")
            .replace("ω0", "$\\omega_0$").replace("±", "$\\pm$").replace("≤", "$\\le$").replace("→", "$\\to$")
            .replace("³", "$^3$").replace("²", "$^2$").replace("°", "\\textdegree{}").replace("|", "$|$")
            .replace("e-1", "e$-$1").replace("[{'tour': 'LPGA', 'club': '3-iron'}]", "LPGA 3-iron")
            .replace("<", "$<$").replace(">", "$>$").replace("^", "\\textasciicircum{}")
            .replace("\x01", "$v_0^2\\sin 2\\theta_0/g$").replace("\x02", "$2v_0/g$"))


rows = "\n".join(f"{c['id']} & {esc(c['name'])} & {esc(c['expected'])} & {esc(c['observed'])} & {'pass' if c['passed'] else 'FAIL'} \\\\"
                 for c in CK["checks"])
(OUT / "checks_table.tex").write_text(rows + "\n")

vr = []
for t in ["PGA", "LPGA"]:
    for r in [x for x in V["validation"] if x["coef_set"] == "raw" and x["tour"] == t]:
        c = row("calibrated", t, r["club"])
        vr.append(f"{t} & {r['club']} & {r['measured_carry_yd']:.0f} & {r['model_carry_yd']:.1f} & {r['carry_err_yd']:+.1f} & "
                  f"{c['model_carry_yd']:.1f} & {c['carry_err_yd']:+.1f} & {r['measured_apex_yd']:.0f}/{r['model_apex_yd']:.1f} & "
                  f"{r['measured_land_deg']:.0f}/{r['model_land_deg']:.1f} & {100 * r['frac_outside']:.0f} \\\\")
(OUT / "validation_table.tex").write_text("\n".join(vr) + "\n")
st = []
for t, c in [("PGA", "Driver"), ("PGA", "7-iron"), ("PGA", "PW"), ("LPGA", "Driver"), ("LPGA", "3-iron")]:
    r = next(x for x in TM if x["tour"] == t and x["club"] == c)
    f = lambda k, fmt: "\\textit{null}" if r[k] is None else format(r[k], fmt)
    st.append(f"{t} & {c} & {f('ball_mph','.0f')} & {f('launch_deg','.1f')} & {f('spin_rpm','.0f')} & {f('apex_yd','.0f')} & "
              f"{f('land_deg','.0f')} & {f('carry_yd','.0f')} & {f('S0','.4f')} & {r['complete']} \\\\")
(OUT / "sample_table.tex").write_text("\n".join(st) + "\n")
print(f"wrote report/numbers.tex ({len(mac)} macros), checks_table.tex, validation_table.tex")
